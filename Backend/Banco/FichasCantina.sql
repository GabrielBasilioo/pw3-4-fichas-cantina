CREATE DATABASE FICHAS_CANTINAS;

USE FICHAS_CANTINAS;

CREATE TABLE TBL_CARTEIRINHA(
	ID_CARTEIRINHA	BIGINT	IDENTITY(1, 1) NOT NULL,
